import { chromium } from 'playwright';
import { build } from 'esbuild';
import assert from 'node:assert/strict';
const base = process.env.ATLAS_VERIFY_URL || 'http://127.0.0.1:5173';
const bundle = await build({stdin:{contents:`import React from 'react';import{createRoot}from'react-dom/client';import{Rankings}from'./src/components/Rankings';const rows=[{g0:'One-session group',level:0,n:1,fill_rate:.8},{g0:'Two-session group',level:0,n:2,fill_rate:.6},{g0:'Six-session group',level:0,n:6,fill_rate:.4}];createRoot(document.getElementById('root')).render(<Rankings rows={rows} groups={['location']} columns={['fill_rate']} onDrill={()=>{}}/>);`,resolveDir:process.cwd(),loader:'tsx'},bundle:true,write:false,format:'iife',jsx:'automatic',loader:{'.css':'empty'},define:{'import.meta.env.DEV':'false'},plugins:[{name:'fixture-url-imports',setup(b){b.onResolve({filter:/\?url$/},a=>({path:a.path,namespace:'fixture-url'}));b.onLoad({filter:/.*/,namespace:'fixture-url'},()=>({contents:'export default "";',loader:'js'}));}}]});
const browser = await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 await page.goto(base);
 await page.getByRole('button',{name:'Metric definitions',exact:true}).click();
 const doc=page.frameLocator('iframe[title="Atlas metric definition document"]');
 await doc.getByRole('heading',{name:'Metric definitions & calculation methods',exact:true}).waitFor();
 assert.equal(await doc.locator('details[data-domain]').count(),175);
 assert.equal(await doc.locator('details[data-domain] summary').filter({hasText:'(Derived)'}).count(),0);
 await doc.getByLabel('Search metric definitions').fill('same_day_share');
 const sameDay=doc.locator('details[data-metric-id="same_day_share"]');
 await sameDay.locator(':scope > summary').click();
 assert.match(await sameDay.innerText(),/Bookings within 24 hours/);
 assert.match(await sameDay.innerText(),/How we calculate it/);
 assert.equal(await sameDay.locator('.technical').getAttribute('open'), null);
 await sameDay.locator('.technical > summary').click();
 assert.match(await sameDay.innerText(),/not the same calendar day/);
 await sameDay.locator('.technical > summary').click();
 assert.doesNotMatch(await sameDay.innerText(),/Minimum sample:|Ranking minimum:/);
 await sameDay.locator(':scope > summary').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/atlas-metric-review-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await doc.locator('html').evaluate(el=>el.scrollWidth>el.clientWidth+1),false);
 await sameDay.locator(':scope > summary').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/atlas-metric-review-mobile.png'});
 const markdown=await page.request.get(base+'/reference/metric-definitions.md');
 assert.equal(markdown.status(),200);
 assert.match(await markdown.text(),/Full filtered dataset/);
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/?tab=11');
 await page.locator('#data-quality-metric-definitions').waitFor();
 assert.equal(await page.locator('.loader-shell').count(),0,'Source loading must not block the reference');
 assert.equal(await page.locator('main').getAttribute('aria-busy'),'false');
 const qualityDoc=page.frameLocator('#data-quality-metric-definitions iframe');
 await qualityDoc.getByRole('heading',{name:'Metric definitions & calculation methods',exact:true}).waitFor();
 assert.equal(await qualityDoc.locator('[data-metric-id]').count(),175);
 await qualityDoc.getByLabel('Search metric definitions').fill('fill_rate');
 const fill=qualityDoc.locator('[data-metric-id="fill_rate"]');
 await fill.locator(':scope > summary').click();
 assert.match(await fill.innerText(),/attendance|attend/i);
 assert.equal(await fill.locator('.technical').getAttribute('open'),null);
 await fill.locator(':scope > summary').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/atlas-data-quality-definitions-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await qualityDoc.locator('html').evaluate(el=>el.scrollWidth>el.clientWidth+1),false);
 await fill.locator(':scope > summary').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/atlas-data-quality-definitions-mobile.png'});
 // Isolated real Rankings component verifies user-controlled cutoff independently of source loading.
 await page.route('http://rankings.test/**',route=>route.fulfill({contentType:'text/html',body:'<div id="root"></div>'}));
 await page.goto('http://rankings.test/');
 await page.addScriptTag({content:bundle.outputFiles[0].text});
 const minimum=page.getByLabel('Ranking minimum group size');
 await minimum.waitFor();
 assert.equal(await minimum.inputValue(),'0');
 assert.ok((await page.locator('.ranking-item').allTextContents()).some(t=>t.includes('One-session group')));
 await minimum.fill('3');
 assert.equal(await page.locator('.ranking-item').filter({hasText:'One-session group'}).count(),0);
 assert.equal(await page.locator('.ranking-item').filter({hasText:'Two-session group'}).count(),0);
 assert.ok(await page.locator('.ranking-item').filter({hasText:'Six-session group'}).count()>0);
 await minimum.fill('0');
 assert.ok(await page.locator('.ranking-item').filter({hasText:'One-session group'}).count()>0);
 console.log('PASS: 175 document entries, reviewed 24-hour definition, no threshold-derived names/minimum fields, Markdown access, desktop/mobile reference, and user-controlled ranking cutoff/reset.');
} finally {await browser.close();}
